"""Markdown report for the historical matchup demonstration (all numbers read from saved outputs)."""

from __future__ import annotations

import os
from pathlib import Path

import numpy as np
import pandas as pd

from nba_sim.data.ingest import Dataset
from nba_sim.models import MODEL_DESCRIPTIONS


def _fmt(x, nd=1):
    return "–" if pd.isna(x) else f"{x:.{nd}f}"


def _md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    return "\n".join(lines)


def write_demo_report(info: dict, comp: pd.DataFrame, team_tab: pd.DataFrame, ds: Dataset, path: Path) -> Path:
    gid, date = info["game_id"], info["date"]
    home, away = info["home"], info["away"]
    g = ds.games[ds.games["game_id"] == gid].iloc[0]
    rel = lambda p: os.path.relpath(p, path.parent)  # noqa: E731
    C = comp[comp["model"] == "C"]
    core = C[C["minutes_mean"] >= 12].sort_values(["team", "minutes_mean"], ascending=[True, False])
    L = []
    L.append(f"# Historical matchup demonstration: {away} at {home}, {date}\n")
    L.append("**Question.** What would the models have predicted before this game, and how did those "
             "predictions compare with what happened?\n")
    L.append("All numbers below are generated by `nba-sim demo-historical` from the frozen prediction files "
             f"in `outputs/demo/{gid}/`; nothing is typed by hand.\n")

    L.append("## 1. Game selection\n")
    sel = info.get("selection")
    if sel:
        L.append(f"Selected by a pregame-only rule (the outcome is never consulted): {sel['rule']}\n")
        L.append(f"- {sel['n_candidates']} games satisfied the history requirement; the chosen game had the "
                 f"highest combined pregame win percentage ({home} {sel['home_pregame_wpct']:.3f}, "
                 f"{away} {sel['away_pregame_wpct']:.3f}) with {sel['core_players']} core players.\n")
    else:
        L.append(f"Game id {gid} was passed explicitly with `--game-id`.\n")

    L.append("## 2. Information cutoff and protocol\n")
    pm = info["prediction_meta"]["C"]
    L.append(f"- **Cutoff:** {pm['information_cutoff']}. Training rows end on {pm['train_date_max']} "
             f"({pm['n_train_rows']:,} player-games from seasons {', '.join(pm['train_seasons'])}).")
    L.append("- The target game's rows were rebuilt with every outcome field empty, from data cut strictly before "
             "the game date (`simulation/pregame.py`); the game id is asserted absent from training.")
    L.append("- **Pregame information used:** schedule (date, home/away, opponent) and the game's active list. "
             "The active list comes from the box score; the official inactive list is published before tip-off, "
             "but this dataset has no timestamp for it, so this is an *assumption* that it was known. Starting "
             "lineups, injury reports, and betting lines were NOT used.")
    L.append(f"- **Simulations:** exactly {info['n_simulations']:,} joint draws per model, seed sequence "
             f"[{info['seed']}, model index]. Predictions were written and SHA-256 hashed at "
             f"{info['frozen']['frozen_utc']} before the box score was loaded; hashes were re-verified before "
             "scoring:\n")
    L.append(_md_table(pd.DataFrame([{"model": k, "sha256 (predictions .npz)": f"`{v[:16]}…`"}
                                     for k, v in info["frozen"]["sha256"].items()])))
    L.append("\nModels: " + "; ".join(f"**{m}** — {MODEL_DESCRIPTIONS[m]}" for m in info["models"]) + ".\n")

    L.append("## 3. Result\n")
    L.append(f"Final score: {away} {int(g['away_pts'])}, {home} {int(g['home_pts'])}"
             + (f" ({int(g['n_ot'])} OT)" if g["n_ot"] else "") + ".\n")
    tt = team_tab.copy()
    tt["80% interval"] = tt.apply(lambda r: f"{r['pred_lo80']:.0f}–{r['pred_hi80']:.0f}", axis=1)
    tt = tt.rename(columns={"pred_mean": "predicted mean", "pctile": "actual percentile"})
    tt["predicted mean"] = tt["predicted mean"].map(lambda x: f"{x:.1f}")
    tt["actual percentile"] = tt["actual percentile"].map(lambda x: f"{x:.2f}")
    tt["crps"] = tt["crps"].map(lambda x: f"{x:.2f}")
    tt["actual"] = tt["actual"].astype(int)
    L.append("### Team points\n")
    L.append(_md_table(tt[["model", "team", "predicted mean", "80% interval", "actual", "actual percentile", "crps"]]))

    L.append("\n### Players (Model C; players with ≥12 expected minutes)\n")
    L.append("Intervals are central predictive intervals of the discrete distribution; *pct* is the actual "
             "outcome's mid-percentile F(y−1) + ½·p(y) within the frozen distribution.\n")
    for s, label in [("pts", "Points"), ("reb", "Rebounds"), ("ast", "Assists"), ("pra", "Points+Rebounds+Assists"),
                     ("minutes", "Minutes")]:
        nd = 1
        t = pd.DataFrame({
            "player": core["player_name"] + " (" + core["team"] + ")",
            "mean": core[f"{s}_mean"].map(lambda x: _fmt(x, nd)),
            "median": core[f"{s}_median"].map(lambda x: _fmt(x, 0 if s != "minutes" else 1)),
            "50%": core.apply(lambda r: f"{_fmt(r[f'{s}_lo50'], 0)}–{_fmt(r[f'{s}_hi50'], 0)}", axis=1),
            "80%": core.apply(lambda r: f"{_fmt(r[f'{s}_lo80'], 0)}–{_fmt(r[f'{s}_hi80'], 0)}", axis=1),
            "95%": core.apply(lambda r: f"{_fmt(r[f'{s}_lo95'], 0)}–{_fmt(r[f'{s}_hi95'], 0)}", axis=1),
            "actual": core[f"{s}_actual"].map(lambda x: _fmt(x, 1 if s == "minutes" else 0)),
            "pct": core[f"{s}_pctile"].map(lambda x: f"{x:.2f}"),
        })
        L.append(f"**{label}**\n")
        L.append(_md_table(t))
        L.append("")

    L.append("### Predeclared threshold probabilities (Model C)\n")
    L.append("Thresholds are fixed in `configs/default.yaml` (`evaluation.thresholds`) before any run. "
             "✔ = event happened.\n")
    rows = []
    for _, r in core.iterrows():
        rec = {"player": f"{r['player_name']} ({r['team']})"}
        for s, ts in (("pts", [15, 20, 25]), ("reb", [5, 8]), ("ast", [5]), ("pra", [30])):
            for t in ts:
                p = r.get(f"P({s}>={t})")
                if p is None or pd.isna(p):
                    continue
                hit = r[f"{s}_actual"] >= t
                rec[f"{s}≥{t}"] = f"{p:.2f}{' ✔' if hit else ''}"
        rows.append(rec)
    L.append(_md_table(pd.DataFrame(rows).fillna("–")))

    L.append("\n## 4. Model A vs B vs C in this game\n")
    allm = comp[comp["minutes_mean"].notna()]
    ids = set(core["player_id"])
    sub = allm[allm["player_id"].isin(ids)]
    agg = []
    for m, t in sub.groupby("model"):
        rec = {"model": m}
        for s in ["minutes", "pts", "reb", "ast", "pra"]:
            rec[f"CRPS {s}"] = f"{t[f'{s}_crps'].mean():.2f}"
            inside = ((t[f"{s}_actual"] >= t[f"{s}_lo80"]) & (t[f"{s}_actual"] <= t[f"{s}_hi80"])).mean()
            rec[f"in 80% {s}"] = f"{inside:.0%}"
        agg.append(rec)
    L.append(_md_table(pd.DataFrame(agg)))
    L.append(f"\nMean CRPS over the {len(ids)} core players (lower is better). One game is a sample of ~{len(ids)} "
             "correlated player outcomes: these numbers illustrate the forecasts and are **not** evidence about "
             "which model is better. That question is answered by the backtest (`reports/validation_report.md`).\n")

    ctx = info.get("backtest_context")
    L.append("## 5. Calibration context from the full backtest\n")
    if ctx:
        t = pd.DataFrame(ctx["table"])
        t = t[t["model"].isin(info["models"])]
        t["cov50"] = t["cov50"].map(lambda x: f"{x:.3f}")
        t["cov80"] = t["cov80"].map(lambda x: f"{x:.3f}")
        t["cov95"] = t["cov95"].map(lambda x: f"{x:.3f}")
        t["mass80"] = t["mass80"].map(lambda x: f"{x:.3f}")
        t["crps"] = t["crps"].map(lambda x: f"{x:.3f}")
        L.append(f"Empirical coverage of central intervals over all backtest player-games (run `{ctx['run']}`). "
                 "For integer stats the nominal 80% interval carries more than 80% predictive mass "
                 "(`mass80`); calibration means `cov80` ≈ `mass80`.\n")
        L.append(_md_table(t[["model", "stat", "n", "cov50", "cov80", "mass80", "cov95", "crps"]]))
    else:
        L.append("Backtest scores were not available when this report was generated.")

    L.append("\n## 6. Figures\n")
    for k, p in info["figures"].items():
        L.append(f"![{k}]({rel(p)})\n")

    L.append("## 7. Findings\n")
    n = len(core)
    for s in ["pts", "reb", "ast", "minutes"]:
        inside = int(((core[f"{s}_actual"] >= core[f"{s}_lo80"]) & (core[f"{s}_actual"] <= core[f"{s}_hi80"])).sum())
        L.append(f"- {s}: {inside} of {n} core players finished inside Model C's 80% interval.")
    tails = core[(core["pts_pctile"] < 0.05) | (core["pts_pctile"] > 0.95)]
    if len(tails):
        L.append("- Points outcomes in the outer 5% tails of Model C: " + "; ".join(
            f"{r['player_name']} {int(r['pts_actual'])} pts (pct {r['pts_pctile']:.2f}, predicted mean "
            f"{r['pts_mean']:.1f})" for _, r in tails.iterrows()) + ".")
    else:
        L.append("- No core player's points fell in the outer 5% tails of Model C's distribution.")
    L.append("")
    L.append("## 8. Limitations\n")
    L.append("- Single game: illustrative only; see the backtest for evidence.")
    L.append("- The active list is assumed known pregame (see §2). Real-time injury news, minutes restrictions "
             "and lineup announcements are not modelled; a late scratch of a starter would not be reflected.")
    L.append("- The demo models are fit with the information cutoff at the game date; the backtest refits every "
             "14 days, so the backtest's own forecast for this game used a slightly older fit.")
    L.append("- No betting market information is used, and nothing here measures profitability.")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L) + "\n")
    return path
